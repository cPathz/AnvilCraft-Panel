/// Extract the "Minecraft version" category from a NeoForge version string.
fn extract_neoforge_category(nf_version: &str) -> Option<String> {
    if nf_version.starts_with("1.") {
        nf_version.split('-').next().map(|s| s.to_string())
    } else {
        let parts: Vec<&str> = nf_version.split('.').collect();
        if parts.len() >= 2 {
            let major = parts[0].parse::<u32>().unwrap_or(0);
            if major >= 20 && major <= 21 {
                Some(format!("1.{}.{}", parts[0], parts[1]))
            } else {
                let cat = parts[0..parts.len() - 1].join(".");
                Some(cat)
            }
        } else {
            None
        }
    }
}

/// Fetch the maven-metadata.xml once and return its body.
async fn fetch_neoforge_maven_metadata() -> Result<String, String> {
    let url = "https://maven.neoforged.net/releases/net/neoforged/neoforge/maven-metadata.xml";
    let client = reqwest::Client::builder()
        .user_agent("AnvilCraft/1.0")
        .timeout(std::time::Duration::from_secs(30))
        .build()
        .map_err(|e| e.to_string())?;
    client
        .get(url)
        .send()
        .await
        .map_err(|e| format!("Network error: {}", e))?
        .text()
        .await
        .map_err(|e| e.to_string())
}

/// Step 1 of the NeoForge flow: list MC versions that have at least one build.
fn parse_mc_versions_from_xml(xml: &str) -> Vec<String> {
    let mut mc_versions: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for line in xml.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("<version>") && trimmed.ends_with("</version>") {
            let inner = trimmed
                .trim_start_matches("<version>")
                .trim_end_matches("</version>");
            if let Some(ver) = extract_neoforge_category(inner) {
                if ver.split('.').all(|p| p.parse::<u32>().is_ok()) {
                    mc_versions.insert(ver);
                }
            }
        }
    }
    let mut result: Vec<String> = mc_versions.into_iter().collect();
    result.reverse();
    result
}

/// Step 2 of the NeoForge flow: list NeoForge builds for an MC version.
fn parse_builds_from_xml(xml: &str, mc_version: &str, betas: bool) -> Vec<String> {
    let mut versions: Vec<String> = Vec::new();
    for line in xml.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("<version>") && trimmed.ends_with("</version>") {
            let inner = trimmed
                .trim_start_matches("<version>")
                .trim_end_matches("</version>");
            if let Some(ver) = extract_neoforge_category(inner) {
                if ver == mc_version {
                    let is_beta = inner.contains("-beta");
                    if betas || !is_beta {
                        versions.push(inner.to_string());
                    }
                }
            }
        }
    }
    versions.reverse();
    versions
}

/// Run the NeoForge installer JAR headlessly and stream stderr/stdout as
/// `install-progress` events. Emits Done on success.
async fn run_neoforge_installer(
    app: &tauri::AppHandle,
    id: &str,
    neoforge_version: &str,
    minecraft_dir: &Path,
) -> Result<(), String> {
    let installer_url = format!(
        "https://maven.neoforged.net/releases/net/neoforged/neoforge/{}/neoforge-{}-installer.jar",
        neoforge_version, neoforge_version
    );
    let installer_path = minecraft_dir.join(format!("neoforge-{}-installer.jar", neoforge_version));
    fs::create_dir_all(minecraft_dir).map_err(|e| e.to_string())?;

    let _ = app.emit(
        "install-progress",
        InstanceInstallProgress {
            id: id.to_string(),
            step: format!("Downloading NeoForge {} installer...", neoforge_version),
            progress: 0,
            total_size: None,
            downloaded: 0,
        },
    );

    let log_file = minecraft_dir
        .parent()
        .unwrap_or(minecraft_dir)
        .join("install.log");

    download_file(app, &installer_url, &installer_path, id, None, Some(&log_file)).await?;

    let _ = app.emit(
        "install-progress",
        InstanceInstallProgress {
            id: id.to_string(),
            step: format!("Ejecutando instalador NeoForge {}...", neoforge_version),
            progress: 50,
            total_size: None,
            downloaded: 0,
        },
    );

    if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&log_file) {
        let _ = writeln!(
            f,
            "[{}] Running NeoForge installer headlessly...",
            chrono::Local::now().format("%H:%M:%S")
        );
    }

    let java_exe = crate::commands::java::find_any_java_executable(app).ok_or_else(|| {
        "Java not found. Install a Java runtime from Settings \u{2192} Portable Java, or set the JAVA_HOME environment variable.".to_string()
    })?;
    let mut std_cmd = std::process::Command::new(&java_exe);
    std_cmd
        .arg("-jar")
        .arg(&installer_path)
        .arg("--installServer")
        .current_dir(minecraft_dir)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped());

    #[cfg(windows)]
    std_cmd.creation_flags(0x08000000);

    let mut cmd = tokio::process::Command::from(std_cmd);
    let mut child = cmd
        .spawn()
        .map_err(|e| format!("Failed to run NeoForge installer: {}", e))?;

    let app_for_stderr = app.clone();
    let id_for_stderr = id.to_string();
    let stderr_log = log_file.clone();
    let stderr_handle = if let Some(stderr) = child.stderr.take() {
        Some(tokio::spawn(async move {
            use tokio::io::AsyncBufReadExt;
            let mut reader = tokio::io::BufReader::new(stderr).lines();
            let mut line_count: u64 = 0;
            while let Ok(Some(line)) = reader.next_line().await {
                line_count += 1;
                if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&stderr_log) {
                    let _ = writeln!(f, "[STDERR] {}", line);
                }
                if line_count % 3 == 0 || line.contains("Complete") || line.contains("Installing") {
                    let mut short_line = line.clone();
                    if short_line.len() > 60 {
                        short_line.truncate(60);
                        short_line.push_str("...");
                    }
                    let simulated_progress = 50 + (line_count.min(180) / 4);
                    let _ = app_for_stderr.emit(
                        "install-progress",
                        InstanceInstallProgress {
                            id: id_for_stderr.clone(),
                            step: format!("NeoForge: {}", short_line),
                            progress: simulated_progress as u64,
                            total_size: None,
                            downloaded: 0,
                        },
                    );
                }
            }
        }))
    } else {
        None
    };

    let stdout_log = log_file.clone();
    let app_for_stdout = app.clone();
    let id_for_stdout = id.to_string();
    let stdout_handle = if let Some(stdout) = child.stdout.take() {
        Some(tokio::spawn(async move {
            use tokio::io::AsyncBufReadExt;
            let mut reader = tokio::io::BufReader::new(stdout).lines();
            let mut line_count: u64 = 0;
            while let Ok(Some(line)) = reader.next_line().await {
                line_count += 1;
                if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&stdout_log) {
                    let _ = writeln!(f, "{}", line);
                }
                if line_count % 3 == 0 || line.contains("Complete") || line.contains("Installing") {
                    let mut short_line = line.clone();
                    if short_line.len() > 60 {
                        short_line.truncate(60);
                        short_line.push_str("...");
                    }
                    let simulated_progress = 50 + (line_count.min(180) / 4);
                    let _ = app_for_stdout.emit(
                        "install-progress",
                        InstanceInstallProgress {
                            id: id_for_stdout.clone(),
                            step: format!("NeoForge: {}", short_line),
                            progress: simulated_progress as u64,
                            total_size: None,
                            downloaded: 0,
                        },
                    );
                }
            }
        }))
    } else {
        None
    };

    let status = child
        .wait()
        .await
        .map_err(|e| format!("Failed to wait for NeoForge installer: {}", e))?;

    if let Some(handle) = stderr_handle {
        handle.abort();
    }
    if let Some(handle) = stdout_handle {
        handle.abort();
    }

    if !status.success() {
        return Err("NeoForge installer failed".into());
    }

    let _ = fs::remove_file(&installer_path);
    let _ = fs::remove_file(
        minecraft_dir.join(format!("neoforge-{}-installer.jar.log", neoforge_version)),
    );

    tokio::time::sleep(std::time::Duration::from_millis(1000)).await;

    let _ = app.emit(
        "install-progress",
        InstanceInstallProgress {
            id: id.to_string(),
            step: "Done".into(),
            progress: 100,
            total_size: None,
            downloaded: 0,
        },
    );

    Ok(())
}

pub struct NeoForgeLoader;

impl NeoForgeLoader {
    /// List MC versions that have at least one NeoForge build. Used by the
    /// `get_neoforge_mc_versions` Tauri command.
    pub async fn list_mc_versions() -> Result<Vec<String>, String> {
        let xml = fetch_neoforge_maven_metadata().await?;
        Ok(parse_mc_versions_from_xml(&xml))
    }

    /// List NeoForge builds for a given MC version. Used by the
    /// `get_neoforge_versions` Tauri command. `betas=true` includes
    /// `-beta` suffixed builds.
    pub async fn list_builds(mc_version: &str, betas: bool) -> Result<Vec<String>, String> {
        let xml = fetch_neoforge_maven_metadata().await?;
        Ok(parse_builds_from_xml(&xml, mc_version, betas))
    }
}

#[async_trait]
impl LoaderStrategy for NeoForgeLoader {
    fn engine(&self) -> InstanceEngine {
        InstanceEngine::NeoForge
    }
    fn category(&self) -> LoaderCategory {
        LoaderCategory::Mods
    }
    fn display_name(&self) -> &'static str {
        "NeoForge"
    }
    fn min_java(&self) -> u8 {
        17
    }
    fn capabilities(&self) -> LoaderCapabilities {
        mods_capabilities()
    }

    fn is_two_step_version(&self) -> bool {
        true
    }

    async fn fetch_mc_versions(&self) -> Result<Vec<String>, String> {
        Self::list_mc_versions().await
    }

    async fn fetch_versions(
        &self,
        mc_version: Option<&str>,
    ) -> Result<Vec<VersionMeta>, String> {
        let mc = mc_version
            .ok_or("NeoForge requires an MC version before fetching builds")?;
        let builds = Self::list_builds(mc, true).await?;
        Ok(builds
            .into_iter()
            .map(|b| VersionMeta {
                id: b.clone(),
                build: Some(b.clone()),
                url: None,
                display_name: b,
                requires_mc_version: Some(mc.to_string()),
            })
            .collect())
    }

    async fn resolve_download(&self, version: &VersionMeta) -> Result<DownloadInfo, String> {
        let installer_url = format!(
            "https://maven.neoforged.net/releases/net/neoforged/neoforge/{}/neoforge-{}-installer.jar",
            version.id, version.id
        );
        Ok(DownloadInfo {
            url: installer_url,
            filename: format!("neoforge-{}-installer.jar", version.id),
            size: None,
        })
    }

    async fn install(
        &self,
        app: &tauri::AppHandle,
        id: &str,
        target_dir: &Path,
        version: &VersionMeta,
        _custom_url: Option<&str>,
        accept_eula: bool,
    ) -> Result<(), String> {
        let mc_dir = target_dir.join(".minecraft");
        run_neoforge_installer(app, id, &version.id, &mc_dir).await?;
        write_eula_txt(mc_dir.join("eula.txt"), accept_eula)?;
        Ok(())
    }
}

