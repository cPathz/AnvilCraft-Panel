//! Mods-family loaders (NeoForge, Forge, Fabric, Quilt).
//!
//! NeoForge is the only loader in the project that uses the
//! `is_two_step_version()` flow: the user first picks an MC version, then
//! picks a NeoForge build for that MC version. The other three are
//! single-step (one version id → one install).
//!
//! `find_forge_args_file` lives here as `pub(crate)` because both
//! `start_instance` (in `commands/server.rs`) and the launch flow need to
