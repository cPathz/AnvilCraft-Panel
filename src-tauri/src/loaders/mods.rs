pub struct ForgeLoader;

#[async_trait]
impl LoaderStrategy for ForgeLoader {
    fn engine(&self) -> InstanceEngine {
        InstanceEngine::Forge
    }
    fn category(&self) -> LoaderCategory {
        LoaderCategory::Mods
    }
    fn display_name(&self) -> &'static str {
        "Forge"
    }
    fn min_java(&self) -> u8 {
        17
    }
    fn capabilities(&self) -> LoaderCapabilities {
        mods_capabilities()
    }

    async fn fetch_versions(
        &self,
        _mc_version: Option<&str>,
    ) -> Result<Vec<VersionMeta>, String> {
        // Delegate to the project-versions shortcut, which already hits the
        // Forge maven-metadata.xml. Mapping to `VersionMeta` keeps the rest of
        // the install pipeline (which reads `url`) working without duplicating
        // the HTTP/regex logic.
        let versions = crate::commands::versions::get_project_versions("forge".to_string()).await?;
        Ok(versions
            .into_iter()
            .map(|combined| {
                // Combined id is "mc_version-forge_version" (e.g.
                // "1.21.11-61.1.14"). The installer URL embeds it twice:
                //   https://maven.minecraftforge.net/net/minecraftforge/forge/{combined}/forge-{combined}-installer.jar
                let mc_version = combined.split('-').next().unwrap_or("").to_string();
                let url = format!(
                    "https://maven.minecraftforge.net/net/minecraftforge/forge/{}/forge-{}-installer.jar",
                    combined, combined
                );
                VersionMeta {
                    id: combined.clone(),
                    build: None,
                    url: Some(url),
                    display_name: combined,
                    requires_mc_version: if mc_version.is_empty() { None } else { Some(mc_version) },
                }
            })
            .collect())
    }

    async fn install(
        &self,
        app: &tauri::AppHandle,
        id: &str,
        target_dir: &Path,
        version: &VersionMeta,
        _custom_url: Option<&str>,
        accept_eula: bool,
    ) -> Result<(), String> {
        // Forge combined version is "mc_version-forge_version"
        // (e.g. "1.20.1-47.2.0"). The installer URL is:
        // https://maven.minecraftforge.net/net/minecraftforge/forge/{ver}/forge-{ver}-installer.jar
        let combined = &version.id;
        let installer_url = format!(
            "https://maven.minecraftforge.net/net/minecraftforge/forge/{}/forge-{}-installer.jar",
            combined, combined
        );
        let mc_dir = target_dir.join(".minecraft");
        fs::create_dir_all(&mc_dir).map_err(|e| e.to_string())?;
        let installer_path = mc_dir.join(format!("forge-{}-installer.jar", combined));
        let log_file = mc_dir.parent().unwrap_or(&mc_dir).join("install.log");

        download_file(app, &installer_url, &installer_path, id, None, Some(&log_file)).await?;

        let _ = app.emit(
            "install-progress",
            InstanceInstallProgress {
                id: id.to_string(),
                step: format!("Ejecutando instalador Forge {}...", combined),
                progress: 50,
                total_size: None,
                downloaded: 0,
            },
        );

        if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&log_file) {
            let _ = writeln!(
                f,
                "[{}] Running Forge installer headlessly...",
                chrono::Local::now().format("%H:%M:%S")
            );
        }

        // Run installer headlessly
        let java_exe = crate::commands::java::find_any_java_executable(app).ok_or_else(|| {
            "Java not found. Install a Java runtime from Settings \u{2192} Portable Java, or set the JAVA_HOME environment variable.".to_string()
        })?;
        let mut std_cmd = std::process::Command::new(&java_exe);
        std_cmd
            .arg("-jar")
            .arg(&installer_path)
            .arg("--installServer")
            .current_dir(&mc_dir)
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped());
        #[cfg(windows)]
        std_cmd.creation_flags(0x08000000);

        let mut cmd = tokio::process::Command::from(std_cmd);
        let mut child = cmd
            .spawn()
            .map_err(|e| format!("Failed to run Forge installer: {}", e))?;

        // Drain stderr — child.stderr.take() prevents the OS pipe buffer
        // (~64KB) from filling up and blocking the child.
        let app_for_stderr = app.clone();
        let id_for_stderr = id.to_string();
        let stderr_log = log_file.clone();
        let stderr_handle = if let Some(stderr) = child.stderr.take() {
            Some(tokio::spawn(async move {
                use tokio::io::AsyncBufReadExt;
                let mut reader = tokio::io::BufReader::new(stderr).lines();
                let mut line_count: u64 = 0;
                while let Ok(Some(line)) = reader.next_line().await {
                    line_count += 1;
                    if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&stderr_log) {
                        let _ = writeln!(
                            f,
                            "[{}] [STDERR] {}",
                            chrono::Local::now().format("%H:%M:%S"),
                            line
                        );
                    }
                    if line_count % 3 == 0
                        || line.contains("Complete")
                        || line.contains("Installing")
                        || line.contains("Downloading")
                        || line.contains("Patching")
                    {
                        let mut short_line = line.clone();
                        if short_line.len() > 60 {
                            short_line.truncate(60);
                            short_line.push_str("...");
                        }
                        let simulated_progress = 50 + (line_count.min(180) / 4);
                        let _ = app_for_stderr.emit(
                            "install-progress",
                            InstanceInstallProgress {
                                id: id_for_stderr.clone(),
                                step: format!("Forge: {}", short_line),
                                progress: simulated_progress as u64,
                                total_size: None,
                                downloaded: 0,
                            },
                        );
                    }
                }
            }))
        } else {
            None
        };

        // Drain stdout — same pattern, no STDERR prefix.
        let stdout_log = log_file.clone();
        let app_for_stdout = app.clone();
        let id_for_stdout = id.to_string();
        let stdout_handle = if let Some(stdout) = child.stdout.take() {
            Some(tokio::spawn(async move {
                use tokio::io::AsyncBufReadExt;
                let mut reader = tokio::io::BufReader::new(stdout).lines();
                let mut line_count: u64 = 0;
                while let Ok(Some(line)) = reader.next_line().await {
                    line_count += 1;
                    if let Ok(mut f) = fs::OpenOptions::new().append(true).open(&stdout_log) {
                        let _ = writeln!(
                            f,
                            "[{}] {}",
                            chrono::Local::now().format("%H:%M:%S"),
                            line
                        );
                    }
                    if line_count % 3 == 0
                        || line.contains("Complete")
                        || line.contains("Installing")
                        || line.contains("Downloading")
                        || line.contains("Patching")
                    {
                        let mut short_line = line.clone();
                        if short_line.len() > 60 {
                            short_line.truncate(60);
                            short_line.push_str("...");
                        }
                        let simulated_progress = 50 + (line_count.min(180) / 4);
                        let _ = app_for_stdout.emit(
                            "install-progress",
                            InstanceInstallProgress {
                                id: id_for_stdout.clone(),
                                step: format!("Forge: {}", short_line),
                                progress: simulated_progress as u64,
                                total_size: None,
                                downloaded: 0,
                            },
                        );
                    }
                }
            }))
        } else {
            None
        };

        let status = child
            .wait()
            .await
            .map_err(|e| format!("Failed to wait for Forge installer: {}", e))?;

        if let Some(handle) = stderr_handle {
            handle.abort();
        }
        if let Some(handle) = stdout_handle {
            handle.abort();
        }

        // NOTE: installer JAR is intentionally NOT removed — keep it around
        // for debug if something goes wrong. NeoForge does delete it, but
        // Forge's install hangs are easier to investigate with the JAR still
        // on disk. Follow-up can re-enable deletion once this is stable.
        if !status.success() {
            return Err("Forge installer failed".into());
        }

        write_eula_txt(mc_dir.join("eula.txt"), accept_eula)?;

        let _ = app.emit(
            "install-progress",
            InstanceInstallProgress {
                id: id.to_string(),
                step: "Done".into(),
                progress: 100,
                total_size: None,
                downloaded: 0,
            },
        );

        Ok(())
    }
}

